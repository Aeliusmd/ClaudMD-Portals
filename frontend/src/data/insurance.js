/** Short code stamped on the document thumbnail (Doctor First Report, Work Status Report, ...). */
function doc(id, badge, title, visitDate, documentId) {
  return {
    id,
    previewBadge: badge,
    title,
    visitDate,
    reportDate: visitDate,
    documentId,
    url: SAMPLE_DOCUMENT_URL,
  };
}

